const cache = new Map<string, HTMLCanvasElement>();

function hex(c: number): string {
  return '#' + c.toString(16).padStart(6, '0');
}

export function kindColor(c: CardDef): string {
  return c.kind === 'proj' ? '#2e4a8a' : c.kind === 'mod' ? '#2e6a3a' : '#6a2e6a';
}

export function cardIcon(id: string): HTMLCanvasElement {
  const hit = cache.get(id);
  if (hit) return hit;
  const c = card(id);
  const cv = document.createElement('canvas');
  cv.width = 12;
  cv.height = 12;
  const ctx = cv.getContext('2d')!;
  ctx.fillStyle = kindColor(c);
  ctx.fillRect(0, 0, 12, 12);
  ctx.fillStyle = 'rgba(0,0,0,0.35)';
  ctx.fillRect(1, 1, 10, 10);
  const pat = G[id] ?? G.spark;
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const ch = pat[y][x];
      if (ch === '#') {
        ctx.fillStyle = hex(c.color);
        ctx.fillRect(2 + x, 2 + y, 1, 1);
      } else if (ch === 'o') {
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(2 + x, 2 + y, 1, 1);
      }
    }
  }
  cache.set(id, cv);
  return cv;
}

export function drawCard(ctx: CanvasRenderingContext2D, id: string, x: number, y: number, size = 12): void {
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(cardIcon(id), x, y, size, size);
}
