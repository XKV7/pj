// 터치 스모크 테스트: 모바일 가로 화면에서 탭으로 시작 → 조이스틱 이동 → 시전 → 가방/일시정지.
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
const PORT = 5183;
const server = spawn('node', ['node_modules/vite/bin/vite.js', '--port', String(PORT), '--strictPort'], { stdio: ['ignore', 'pipe', 'pipe'] });
await new Promise((res) => server.stdout.on('data', (d) => String(d).includes('Local') && res()));
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(`http://localhost:${PORT}/`);
await page.waitForTimeout(1200);
const rect = await page.evaluate(() => { const r = document.getElementById('screen').getBoundingClientRect(); return { x: r.left, y: r.top, s: r.width / 400 }; });
const P = (x, y) => ({ x: rect.x + x * rect.s, y: rect.y + y * rect.s });
// CDP 멀티터치
const cdp = await ctx.newCDPSession(page);
const touch = async (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map((p, i) => ({ ...P(p[0], p[1]), id: p[2] ?? i })) });
const tap = async (x, y) => { await touch('touchStart', [[x, y]]); await page.waitForTimeout(60); await touch('touchEnd', []); await page.waitForTimeout(150); };
await tap(200, 102);
await page.waitForTimeout(800);
const st = () => page.evaluate(() => window.__app.state);
console.log('state', await st());
const x0 = await page.evaluate(() => window.__app.game.player.body.x);
await touch('touchStart', [[48 + 20, 158, 1]]);
await page.waitForTimeout(900);
const x1 = await page.evaluate(() => window.__app.game.player.body.x);
await touch('touchStart', [[48 + 20, 158, 1], [300, 130, 2]]);
await page.waitForTimeout(600);
const mana = await page.evaluate(() => window.__app.game.player.wand.mana);
await page.screenshot({ path: 'screenshots/touch-game.png' });
await touch('touchEnd', []);
console.log('moved', Math.round(x1 - x0), 'mana after cast', Math.round(mana));
// 조준 조이스틱: 누른 채 왼쪽 위로 → 조준선 → 떼면 발사
await page.waitForTimeout(600);
const m0 = await page.evaluate(() => window.__app.game.player.wand.mana);
await touch('touchStart', [[346, 150, 5]]);
await page.waitForTimeout(80);
await touch('touchMove', [[346 - 20, 150 - 12, 5]]);
await page.waitForTimeout(500);
const mh = await page.evaluate(() => window.__app.game.player.wand.mana);
const aimA = await page.evaluate(() => window.__app.game.player.aimAngle);
await page.screenshot({ path: 'screenshots/touch-aim.png' });
await touch('touchEnd', []);
await page.waitForTimeout(100);
const m1 = await page.evaluate(() => window.__app.game.player.wand.mana);
console.log('aim angle', aimA.toFixed(2), 'mana start', Math.round(m0), 'while holding', Math.round(mh), 'after release', Math.round(m1));
const m2 = await page.evaluate(() => window.__app.game.player.wand.mana);
await touch('touchStart', [[346, 150, 6]]);
await page.waitForTimeout(200);
await touch('touchEnd', []);
await page.waitForTimeout(100);
console.log('cancel: mana', Math.round(m2), '->', Math.round(await page.evaluate(() => window.__app.game.player.wand.mana)));
console.log('state before bag', await st(), await page.evaluate(() => window.__app.game.over));
await tap(325, 81);
console.log('after bag', await st());
await page.screenshot({ path: 'screenshots/touch-inventory.png' });
await tap(335, 185);
console.log('after close', await st());
await tap(374, 81);
console.log('after pause', await st());
await tap(200, 92);
console.log('after resume', await st());
console.log('errors', errors);
await browser.close();
server.kill();
process.exit(errors.length ? 1 : 0);
